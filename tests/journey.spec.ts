test('corrupted active records recover from the last valid backup', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Become a Novotian', exact: true }).click()
  await page.getByLabel('Citizen name').fill('Mira')
  await page.getByRole('button', { name: 'Choose a plot' }).click()
  await page.getByRole('button', { name: 'Claim my square' }).click()
  await expect(page.getByRole('heading', { name: 'Novotian passport' })).toBeVisible()
  await page.getByRole('button', { name: 'Close panel' }).click()
  await page.getByRole('button', { name: 'Market', exact: true }).click()
  await page.getByRole('button', { name: /Collect allowance/ }).click()
  await expect.poll(async () => (await save(page)).coins).toBe(85)
  await page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>((ok) => {
      const r = indexedDB.open('novotium-willowmere')
      r.onsuccess = () => ok(r.result)
    })
    await new Promise<void>((ok) => {
      const tx = db.transaction('world', 'readwrite')
      tx.objectStore('world').put({ revision: 2, version: 3, coins: -1 }, 'current')
      tx.oncomplete = () => ok()
    })
    db.close()
  })
  await page.reload()
  await expect(page.getByRole('status')).toContainText('recovery copy')
  await page.getByRole('button', { name: 'Passport', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Mira' })).toBeVisible()
})
