test('two open tabs cannot overwrite one another’s wallet or plot claim', async ({ page, context }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Become a Novotian', exact: true }).click()
  await page.getByLabel('Citizen name').fill('Ash')
  await page.getByRole('button', { name: 'Choose a plot' }).click()
  const second = await context.newPage()
  await second.goto('/')
  await second.getByRole('button', { name: 'Become a Novotian', exact: true }).click()
  await second.getByLabel('Citizen name').fill('Brook')
  await second.getByRole('button', { name: 'Choose a plot' }).click()
  await page.getByRole('button', { name: 'Claim my square' }).click()
  await expect(page.getByRole('heading', { name: 'Novotian passport' })).toBeVisible()
  await second.getByRole('button', { name: 'Claim my square' }).click()
  await expect(second.getByRole('status')).toContainText('Another tab')
  await second.reload()
  await second.getByRole('button', { name: 'Passport', exact: true }).click()
  await expect(second.getByRole('heading', { name: 'Ash' })).toBeVisible()
})
